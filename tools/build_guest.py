#!/usr/bin/env python3
"""Builds a tiny freestanding AArch64 guest from one C file and emits a C++ header with its bytes and symbols.

  build_guest.py --llvm-bin <dir> --src guest.c --out guest_blob.h --base 0x40000000

Compile: clang --target=aarch64-linux-android -ffreestanding -nostdlib; link with ld.lld at --base; flatten with
llvm-objcopy -O binary; symbols from llvm-nm. Used by the tests (spike and loader), never at game run time.
"""
import argparse
import os
import subprocess
import sys
import tempfile


def run(cmd):
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        sys.stderr.write(" ".join(cmd) + "\n" + r.stdout + r.stderr)
        sys.exit(1)
    return r.stdout


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--llvm-bin", required=True)
    ap.add_argument("--src", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--base", default="0x40000000")
    ap.add_argument("--ns", default="guest_blob")
    a = ap.parse_args()
    exe = lambda n: os.path.join(a.llvm_bin, n + (".exe" if os.name == "nt" else ""))
    base = int(a.base, 0)
    with tempfile.TemporaryDirectory() as td:
        obj = os.path.join(td, "g.o")
        elf = os.path.join(td, "g.elf")
        binf = os.path.join(td, "g.bin")
        run([exe("clang"), "--target=aarch64-linux-android21", "-ffreestanding", "-nostdlib", "-fno-builtin",
             "-fno-pic", "-fno-stack-protector", "-fno-unwind-tables", "-fno-asynchronous-unwind-tables",
             "-mno-outline-atomics", "-O2", "-c", a.src, "-o", obj])
        run([exe("ld.lld"), "-nostdlib", "-static", "--build-id=none", "-z", "norelro", "-z", "noseparate-code",
             "-Ttext=0x%x" % base, "-e", "0", obj, "-o", elf])
        run([exe("llvm-objcopy"), "-O", "binary", elf, binf])
        nm = run([exe("llvm-nm"), "--defined-only", elf])
        data = open(binf, "rb").read()
    syms = []
    for line in nm.splitlines():
        parts = line.split()
        if len(parts) == 3 and parts[1] in ("T", "t", "D", "R", "d", "r") and not parts[2].startswith("$"):
            syms.append((parts[2], int(parts[0], 16)))
    syms.sort(key=lambda s: s[1])
    with open(a.out, "w") as f:
        f.write("// Generated by tools/build_guest.py from %s. Do not edit.\n#pragma once\n#include <cstdint>\n"
                % os.path.basename(a.src))
        f.write("namespace %s {\ninline constexpr std::uint64_t kBase = 0x%xull;\n" % (a.ns, base))
        f.write("inline constexpr unsigned char kBytes[] = {\n")
        for i in range(0, len(data), 16):
            f.write("  " + ",".join("0x%02x" % b for b in data[i:i + 16]) + ",\n")
        f.write("};\nstruct Sym { const char* name; std::uint64_t addr; };\ninline constexpr Sym kSyms[] = {\n")
        for n, v in syms:
            f.write('  {"%s", 0x%xull},\n' % (n, v))
        f.write("};\n}  // namespace %s\n" % a.ns)


if __name__ == "__main__":
    main()
